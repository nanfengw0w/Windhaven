import { readFileSync, writeFileSync } from "node:fs";

const addonUrl = new URL(
  import.meta.resolve("three/addons/controls/TransformControls.js"),
);
const source = readFileSync(addonUrl, "utf8");
const license = readFileSync(new URL("../../../LICENSE", addonUrl), "utf8");
const { version } = JSON.parse(
  readFileSync(new URL("../../../package.json", addonUrl), "utf8"),
);
const upstreamImport = /^import \{([^}]+)\} from 'three';/;
if (!upstreamImport.test(source)) {
  throw new Error("Unexpected Three.js TransformControls import");
}

const boundSource = source.replace(
  upstreamImport,
  (_, bindings) =>
    `import { Ry } from "./three-runtime.js";\n\nconst {${bindings}} = Ry;`,
);
writeFileSync(
  new URL("../src/vendor/transform-controls.js", import.meta.url),
  `// Generated by tooling/build-transform-controls.mjs from three@${version}.
// Uses the same Three.js runtime as the rest of Windhaven.
/*
${license.trimEnd()}
*/
${boundSource}`,
);
